uint32_t fb_color(uint8_t r,uint8_t g,uint8_t b){ return (r<<16)|(g<<8)|b; }

/* retorna 0 se framebuffer ativo (w/h preenchidas), -1 se ausente */
int fb_get_dim(uint32_t *w, uint32_t *h){
    if(!g_fb.addr) return -1;
    if(w) *w=(uint32_t)g_fb.width;
    if(h) *h=(uint32_t)g_fb.height;
    return 0;
}

void fb_init(thais_fb_t *fb){
    g_fb=*fb;
    fb_clear(bg_color);
}

void fb_clear(uint32_t color){
    if(!g_fb.addr) return;
    for(uint64_t y=0;y<g_fb.height;y++){
        uint32_t *row=(uint32_t*)((uint8_t*)g_fb.addr + y*g_fb.pitch);
        for(uint64_t x=0;x<g_fb.width;x++) row[x]=color;
    }
}

void fb_draw_rect(int x,int y,int w,int h,uint32_t color){
    if(!g_fb.addr) return;
    for(int j=y;j<y+h;j++) if(j>=0 && (uint64_t)j<g_fb.height)
        for(int i=x;i<x+w;i++) if(i>=0 && (uint64_t)i<g_fb.width){
            uint32_t *px=(uint32_t*)((uint8_t*)g_fb.addr + j*g_fb.pitch + i*4); *px=color;
        }
}

