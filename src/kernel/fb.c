void fb_draw_char(int x,int y,char c,uint32_t fg,uint32_t bg){
    if(!g_fb.addr) return;
    uint8_t ch=(uint8_t)c;
    int gi;
    if(ch>=32 && ch<=126) gi = ch-32;
    else if(ch==0) return;
    else gi = 63-32;
    for(int row=0;row<16;row++){
        uint8_t bits=font[gi][row];
        for(int col=0;col<8;col++){
            uint32_t colr=(bits&(0x80>>col))?fg:bg;
            int px=x+col, py=y+row;
            if(px>=0 && py>=0 && (uint64_t)px<g_fb.width && (uint64_t)py<g_fb.height){
                uint32_t *p=(uint32_t*)((uint8_t*)g_fb.addr + (uint64_t)py*g_fb.pitch + (uint64_t)px*4);
                *p=colr;
            }
        }
    }
}

void fb_draw_char_scaled(int x,int y,char c,uint32_t fg,uint32_t bg,int scale){
    if(scale<=1){ fb_draw_char(x,y,c,fg,bg); return; }
    if(!g_fb.addr) return;
    uint8_t ch=(uint8_t)c;
    int gi;
    if(ch>=32 && ch<=126) gi = ch-32;
    else if(ch==0) return;
    else gi = 63-32;
    for(int row=0;row<16;row++){
        uint8_t bits=font[gi][row];
        for(int col=0;col<8;col++){
            uint32_t colr=(bits&(0x80>>col))?fg:bg;
            for(int sy=0;sy<scale;sy++) for(int sx=0;sx<scale;sx++){
                int px=x+col*scale+sx, py=y+row*scale+sy;
                if(px>=0 && py>=0 && (uint64_t)px<g_fb.width && (uint64_t)py<g_fb.height){
                    uint32_t *p=(uint32_t*)((uint8_t*)g_fb.addr + (uint64_t)py*g_fb.pitch + (uint64_t)px*4);
                    *p=colr;
                }
            }
        }
    }
}

void fb_draw_text(int x,int y,const char *s,uint32_t fg,uint32_t bg){
    while(*s){ fb_draw_char(x,y,*s,fg,bg); x+=CHAR_W; s++; }
}
void fb_draw_text_scaled(int x,int y,const char *s,uint32_t fg,uint32_t bg,int scale){
    while(*s){ fb_draw_char_scaled(x,y,*s,fg,bg,scale); x+=CHAR_W*scale; s++; }
}

void fb_draw_box_centered(int w,int h,uint32_t bg,uint32_t border){
    if(!g_fb.addr) return;
    int cx=(int)(g_fb.width/2 - w/2);
    int cy=(int)(g_fb.height/2 - h/2);
    fb_draw_rect(cx-2,cy-2,w+4,h+4,border);
    fb_draw_rect(cx,cy,w,h,bg);
}

static void console_scroll(void){
    int rows=(int)(g_fb.height/CHAR_H);
    for(int r=1;r<rows;r++){
        uint32_t *dst=(uint32_t*)((uint8_t*)g_fb.addr + (uint64_t)(r-1)*CHAR_H*g_fb.pitch);
        uint32_t *src=(uint32_t*)((uint8_t*)g_fb.addr + (uint64_t)r*CHAR_H*g_fb.pitch);
        memcpy(dst,src,(uint64_t)CHAR_H*g_fb.pitch);
    }
    uint32_t *last=(uint32_t*)((uint8_t*)g_fb.addr + (uint64_t)(rows-1)*CHAR_H*g_fb.pitch);
    for(uint64_t i=0;i<(uint64_t)CHAR_H*g_fb.width;i++) last[i]=bg_color;
}

void fb_console_init(thais_fb_t *fb){
    g_fb=*fb; console_active=true; cur_x=0; cur_y=0; fb_clear(bg_color);
    boot_console=false;
}

/* consola de BOOT: espelha os kprint do kernel na tela durante a
   inicializacao (visibilidade em hardware fisico sem porta serial).
   fb_console_init (quando o login assume) desliga o espelho. */
void fb_console_activate(void){
    if(!g_fb.addr) return;
    boot_console=true; console_active=true; cur_x=0; cur_y=0; fb_clear(bg_color);
}

/* modo PANIC: independente da fase (boot ou login), leva o texto de
   excecao para a tela — sem isso um fault em hardware real seria invisivel. */
void fb_console_panic(void){
    if(!g_fb.addr) return;
    boot_console=true; console_active=true;
}

bool fb_console_boot_active(void){
    return boot_console;
}

void fb_console_putc(char c){
    if(!console_active) return;
    int cols=(int)(g_fb.width/CHAR_W);
    int rows=(int)(g_fb.height/CHAR_H);
    if(c=='\n'){ cur_x=0; cur_y++; }
    else if(c=='\r'){ cur_x=0; }
    else if(c=='\b'){
        if(cur_x>0){
            cur_x--;
            fb_draw_char(cur_x*CHAR_W, cur_y*CHAR_H, ' ', fg_color, bg_color);
        } else if(cur_y>0){
            cur_y--; cur_x=cols-1;
            fb_draw_char(cur_x*CHAR_W, cur_y*CHAR_H, ' ', fg_color, bg_color);
        }
    }
    else {
        if(cur_x>=cols){ cur_x=0; cur_y++; }
        if((unsigned char)c<32 || (unsigned char)c>126) c='?';
        fb_draw_char(cur_x*CHAR_W, cur_y*CHAR_H, c, fg_color, bg_color);
        cur_x++;
    }
    if(cur_y>=rows){ console_scroll(); cur_y=rows-1; }
}

void fb_console_write(const char *s){ while(*s) fb_console_putc(*s++); }

void fb_console_clear(void){ fb_clear(bg_color); cur_x=0; cur_y=0; }
